"""Embed the local settings UI in PROGMEM. No dependencies, network, or secrets."""
import argparse
import base64
import hashlib
from pathlib import Path
import re


def content_security_policy(html):
    # These exact inline blocks are allowed without enabling arbitrary inline
    # scripts/styles. Keep their whitespace: CSP hashes include every byte.
    sources = {}
    for tag in ('script', 'style'):
        blocks = re.findall(rf'<{tag}>(.*?)</{tag}>', html, re.DOTALL)
        if len(blocks) != 1:
            raise ValueError(f'Expected one inline <{tag}> block in web/index.html')
        digest = hashlib.sha256(blocks[0].encode('utf-8')).digest()
        sources[tag] = base64.b64encode(digest).decode('ascii')
    return (f"default-src 'self'; script-src 'self' 'sha256-{sources['script']}'; "
            f"style-src 'self' 'sha256-{sources['style']}'; connect-src 'self'; "
            "frame-ancestors 'none'; base-uri 'none'; form-action 'self'")


def main():
    root = Path(__file__).resolve().parents[1]
    sketch = root / 'firmware' / 'SEO_Dashboard'
    output = sketch / 'settings_assets.h'
    html = (sketch / 'web' / 'index.html').read_text()
    parts = ['// Generated by tools/embed_settings_web.py; edit web/index.html instead.\n#pragma once\n#include <Arduino.h>\n']
    for symbol, contents in [('SETTINGS_HTML', html), ('SETTINGS_CSP', content_security_policy(html))]:
        if ')SETTINGS"' in contents:
            raise ValueError('Settings source contains the C++ raw-string delimiter')
        parts.append(f'const char {symbol}[] PROGMEM = R"SETTINGS({contents})SETTINGS";\n')
    generated = '\n'.join(parts)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the committed header is stale.')
    args = parser.parse_args()
    if args.check:
        if not output.exists() or output.read_text() != generated:
            raise SystemExit('Settings assets are stale; run python3 tools/embed_settings_web.py')
        print('Settings assets: up to date')
    else:
        output.write_text(generated)
        print('Generated firmware/SEO_Dashboard/settings_assets.h')


if __name__ == '__main__':
    main()
